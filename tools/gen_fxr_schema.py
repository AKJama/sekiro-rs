"""Generates crates/formats/src/fxr_schema.rs: the Sekiro FXR action layouts.

Reads EvenTorset's FXR library action definitions (Unlicense, github.com/EvenTorset/fxr,
`src/actions/*.yml`) and writes, per action id, its name, slot and the names (and field kinds)
of its two field sections and two property sections in the `SDT` (Sekiro) layout.

    uv run -I tools/gen_fxr_schema.py <fxr checkout>/src/actions > crates/formats/src/fxr_schema.rs

Only the parts of the YAML subset those files use are parsed: no YAML library is needed.
"""

import os
import sys


def parse(path):
    lines = open(path, encoding="utf-8").read().split("\n")
    out = {"type": None, "name": None, "slot": None, "props": {}, "games": {}}
    mode = None
    prop = None
    game = None
    key = None
    for raw in lines:
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        indent = len(raw) - len(raw.lstrip())
        text = raw.strip()
        if indent == 0:
            mode = text.rstrip(":").split(":")[0]
            if ":" in text and not text.endswith(":"):
                k, v = text.split(":", 1)
                if k in ("type", "name", "slot"):
                    out[k] = v.strip()
            continue
        if mode == "properties":
            if indent == 2 and text.endswith(":"):
                prop = text[:-1]
                out["props"][prop] = {}
            elif indent == 4 and prop and ":" in text:
                k, v = text.split(":", 1)
                if k == "field":
                    out["props"][prop]["field"] = v.strip()
        elif mode == "games":
            if indent == 2:
                k, _, v = text.partition(":")
                game = k
                out["games"][game] = v.strip() if v.strip() else {}
                key = None
            elif indent == 4 and isinstance(out["games"].get(game), dict):
                k, _, v = text.partition(":")
                key = k
                out["games"][game][key] = v.strip() if v.strip() else []
            elif indent >= 6 and text.startswith("- ") and key is not None:
                out["games"][game][key].append(text[2:].split("#")[0].strip())
    return out


def resolve(action, game, key, depth=0):
    block = action["games"].get(game)
    if depth > 8 or block is None:
        return []
    if isinstance(block, str):
        return resolve(action, block, key, depth + 1)
    value = block.get(key)
    if value is None:
        return []
    if isinstance(value, str):
        return resolve(action, value, key, depth + 1)
    return value


KIND = {"int": 0, "float": 1, "bool": 2, "vec3": 3, "vec4": 4}


def main(directory):
    actions = []
    for name in sorted(os.listdir(directory)):
        if not name.endswith(".yml"):
            continue
        a = parse(os.path.join(directory, name))
        if a["type"] is None:
            continue
        fields = []
        for key in ("fields1", "fields2"):
            fields.append(
                [
                    (n, KIND.get(a["props"].get(n, {}).get("field", "int"), 0))
                    for n in resolve(a, "SDT", key)
                ]
            )
        props = [resolve(a, "SDT", "properties1"), resolve(a, "SDT", "properties2")]
        actions.append((int(a["type"]), a["name"], a["slot"], fields, props))
    actions.sort()
    print("//! Sekiro FXR action layouts, generated by `tools/gen_fxr_schema.py`: do not edit.")
    print("//! Source: EvenTorset's FXR library action definitions (Unlicense).")
    print()
    print("/// Field kinds: 0 int, 1 float, 2 bool, 3 vec3, 4 vec4 (words: 1, 1, 1, 3, 4).")
    print("pub type Field = (&'static str, u8);")
    print()
    print("pub struct ActionSchema {")
    print("    pub id: u16,")
    print("    pub name: &'static str,")
    print("    pub slot: &'static str,")
    print("    pub fields: [&'static [Field]; 2],")
    print("    pub properties: [&'static [&'static str]; 2],")
    print("}")
    print()
    print("pub static ACTIONS: &[ActionSchema] = &[")
    for ident, name, slot, fields, props in actions:
        f = ["&[" + ", ".join(f'("{n}", {k})' for n, k in sec) + "]" for sec in fields]
        p = ["&[" + ", ".join(f'"{n}"' for n in sec) + "]" for sec in props]
        print(
            f'    ActionSchema {{ id: {ident}, name: "{name}", slot: "{slot}", '
            f"fields: [{f[0]}, {f[1]}], properties: [{p[0]}, {p[1]}] }},"
        )
    print("];")
    print()
    print("pub fn action(id: u16) -> Option<&'static ActionSchema> {")
    print("    ACTIONS.binary_search_by_key(&id, |a| a.id).ok().map(|i| &ACTIONS[i])")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])
